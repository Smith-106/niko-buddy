#!/usr/bin/env node
/**
 * P1-IMP-08 — KB-VIEW 消费面同步脚本（hub → QMAI 单仓可构建）
 *
 * 背景：search-adapter.ts 曾跨仓直读 `../reference/REFERENCE-KB-VIEW.json`
 * （niko-hub 工作区文件）。该路径在 QMAI 单仓 checkout / CI 下不存在 → 构建即碎。
 * 本脚本把「检索路由所需的最小消费面」抽出来，落成仓内 generated JSON 并入 git，
 * 使 QMAI 单仓自带数据可构建；content 类大字段不进包。
 *
 * 抽取面（最小消费面）：
 *   - schemaVersion      视图代际（消费方形状断言）
 *   - builtFrom          源视图指纹（漂移/新鲜度断言，缺失即报错）
 *   - routing.agent      intent → collection allowlist（E-01 写作 Agent 面，零 tech）
 *   - collectionCounts   collection → 条目数（routeByQueryIntent 空收藏判定唯一来源，
 *                        替代原先的 collections[c].length —— V7/N-b 连带改动）
 *   - byQueryIntent      intent → 命中条目（检索意图路由观测面）
 *   - collections        仅 {collection,name,trust} 投影 —— P1-IMP-06 buildTrustGradeMap
 *                        消费点所需最小字段集（键序 + 数组序守恒 → trust 映射逐键一致）
 *
 * 用法：
 *   node scripts/sync-kb-view-to-qmai.mjs            # 生成/覆盖 generated JSON
 *   node scripts/sync-kb-view-to-qmai.mjs --check    # 只校验：入 git 产物与源是否一致
 *                                                    #   （含 builtFrom 一致性断言），漂移退出 1
 *   node scripts/sync-kb-view-to-qmai.mjs --source <path> --out <path>
 *
 * 退出码：0 一致/写入成功；1 漂移或缺字段（--check）；2 源不可读/参数错误。
 */
import { mkdirSync, readFileSync, existsSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, "..")

/** 默认源：hub 工作区 reference/（QMAI 的上一级），回退仓内 reference/。 */
const DEFAULT_SOURCE_CANDIDATES = [
  process.env.KB_VIEW_SOURCE,
  resolve(REPO_ROOT, "../reference/REFERENCE-KB-VIEW.json"),
  resolve(REPO_ROOT, "reference/REFERENCE-KB-VIEW.json"),
].filter(Boolean)

const DEFAULT_OUT = resolve(REPO_ROOT, "src/lib/novel/kb/kb-routing-view.generated.json")

/** collections / byQueryIntent 条目投影字段（content 类大字段永不入包）。
 * F4（2026-09-07）：collections 面补 title/domain/query_intent —— 通道 B
 * hay=name+title+domain 中文匹配依赖这些字段（F1 分词后无 hay 即零命中）。 */
const TRUST_ENTRY_FIELDS = ["collection", "name", "trust"]
const COLLECTION_ENTRY_FIELDS = ["collection", "name", "title", "domain", "trust", "query_intent"]
const INTENT_ENTRY_FIELDS = ["collection", "name", "title", "trust", "query_intent"]

const GENERATED_NOTE =
  "GENERATED by scripts/sync-kb-view-to-qmai.mjs — 请勿手改；源 = hub reference/REFERENCE-KB-VIEW.json"

function parseArgs(argv) {
  const opts = { check: false, source: null, out: DEFAULT_OUT, help: false }
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i]
    if (a === "--check") opts.check = true
    else if (a === "--source") opts.source = argv[++i] ?? null
    else if (a === "--out") opts.out = resolve(REPO_ROOT, argv[++i] ?? DEFAULT_OUT)
    else if (a === "--help" || a === "-h") opts.help = true
    else throw new Error(`未知参数：${a}（--help 看用法）`)
  }
  return opts
}

function pickFields(entry, fields) {
  const out = {}
  for (const f of fields) if (entry && f in entry) out[f] = entry[f]
  return out
}

/**
 * 源视图 → 最小消费面。抛错即失败（不静默降级）：消费方依赖 builtFrom /
 * routing.agent / collectionCounts 三者齐备，缺任一都属上游产物缺陷。
 */
export function extractConsumerSurface(source, sourceLabel = "REFERENCE-KB-VIEW.json") {
  const fail = (msg) => {
    throw new Error(`${sourceLabel}: ${msg}`)
  }
  if (!source || typeof source !== "object") fail("视图根不是对象")

  if (typeof source.schemaVersion !== "number") fail("缺少 schemaVersion (number)")
  if (typeof source.builtFrom !== "string" || !source.builtFrom) {
    fail("缺少 builtFrom —— 无指纹视图不可信，拒绝同步（GOV 新鲜度断言）")
  }
  const agent = source.routing?.agent
  if (!agent || typeof agent !== "object") fail("缺少 routing.agent")

  const collectionsIn = source.collections
  if (!collectionsIn || typeof collectionsIn !== "object") {
    fail("缺少 collections（collectionCounts 无从派生）")
  }

  // collectionCounts：数组长度是权威口径（routeByQueryIntent 空收藏判定的唯一来源）。
  // 与源 counts[c] 交叉校验，漂移即失败 —— 防上游两个口径各说各话。
  const collectionCounts = {}
  for (const [name, entries] of Object.entries(collectionsIn)) {
    const len = Array.isArray(entries) ? entries.length : 0
    collectionCounts[name] = len
    const declared = source.counts?.[name]
    if (declared !== undefined && declared !== len) {
      fail(`counts.${name}=${declared} 与 collections.${name}.length=${len} 不一致（上游视图漂移）`)
    }
  }
  // 源 counts 里存在但 collections 缺失的集合（blocked/quarantine 等治理桶）：
  // 保留计数，消费方按 ?? 0 读，不影响路由面。
  for (const [name, declared] of Object.entries(source.counts ?? {})) {
    if (!(name in collectionCounts)) collectionCounts[name] = declared
  }

  // trust 映射投影：键序 + 数组序守恒 → buildTrustGradeMap 首遇规则逐键一致。
  const collections = {}
  for (const [name, entries] of Object.entries(collectionsIn)) {
    collections[name] = (entries ?? []).map((e) => pickFields(e, COLLECTION_ENTRY_FIELDS))
  }

  const byQueryIntent = {}
  for (const [intent, entries] of Object.entries(source.byQueryIntent ?? {})) {
    byQueryIntent[intent] = (entries ?? []).map((e) => pickFields(e, INTENT_ENTRY_FIELDS))
  }

  return {
    _generated: GENERATED_NOTE,
    schemaVersion: source.schemaVersion,
    builtFrom: source.builtFrom,
    routing: { agent },
    collectionCounts,
    byQueryIntent,
    collections,
  }
}

export function serialize(view) {
  return `${JSON.stringify(view, null, 2)}\n`
}

function readJson(path, label) {
  let text
  try {
    text = readFileSync(path, "utf8")
  } catch (err) {
    const e = new Error(`${label} 读取失败：${path} (${err instanceof Error ? err.message : String(err)})`)
    e.code = "SOURCE_UNREADABLE"
    throw e
  }
  try {
    return JSON.parse(text)
  } catch (err) {
    throw new Error(`${label} 不是合法 JSON：${path} (${err instanceof Error ? err.message : String(err)})`)
  }
}

function resolveSourcePath(explicit) {
  if (explicit) {
    const p = resolve(REPO_ROOT, explicit)
    if (!existsSync(p)) {
      const e = new Error(`--source 指定的文件不存在：${p}`)
      e.code = "SOURCE_UNREADABLE"
      throw e
    }
    return p
  }
  for (const cand of DEFAULT_SOURCE_CANDIDATES) {
    if (existsSync(cand)) return cand
  }
  const e = new Error(
    `找不到源视图 REFERENCE-KB-VIEW.json。已尝试：\n  - ${DEFAULT_SOURCE_CANDIDATES.join("\n  - ")}\n` +
      "可用 --source <path> 或环境变量 KB_VIEW_SOURCE 指定。",
  )
  e.code = "SOURCE_UNREADABLE"
  throw e
}

/**
 * --check 的 builtFrom 一致性断言：
 *   1) 入 git 产物必须自带 builtFrom（缺 → 明确报错，不静默）
 *   2) 产物 builtFrom 必须等于源 builtFrom（不等 → 产物过期，需重跑同步）
 */
function assertBuiltFromConsistency(committed, fresh, committedPath, sourcePath) {
  if (!committed || typeof committed !== "object") {
    throw new Error(`产物缺失或非法 JSON：${committedPath}`)
  }
  const a = committed.builtFrom
  const b = fresh.builtFrom
  if (typeof a !== "string" || !a) {
    throw new Error(`产物缺少 builtFrom，无法与源比对（新鲜度断言失败）：${committedPath}`)
  }
  if (a !== b) {
    throw new Error(
      `builtFrom 漂移：产物 ${a} ≠ 源 ${b}\n  源：${sourcePath}\n  请重跑 node scripts/sync-kb-view-to-qmai.mjs 并提交产物。`,
    )
  }
}

function main(argv) {
  const opts = parseArgs(argv)
  if (opts.help) {
    process.stdout.write(
      "用法: node scripts/sync-kb-view-to-qmai.mjs [--check] [--source <path>] [--out <path>]\n" +
        "  默认源: ../reference/REFERENCE-KB-VIEW.json (可用 KB_VIEW_SOURCE 覆盖)\n" +
        "  默认产物: src/lib/novel/kb/kb-routing-view.generated.json\n",
    )
    return 0
  }

  const sourcePath = resolveSourcePath(opts.source)
  const source = readJson(sourcePath, "源视图")
  const fresh = extractConsumerSurface(source, sourcePath)
  const freshText = serialize(fresh)
  const sourceBytes = readFileSync(sourcePath, "utf8").length

  if (opts.check) {
    if (!existsSync(opts.out)) {
      process.stderr.write(`[kb-view-sync] ✗ 产物不存在：${opts.out}\n`)
      return 1
    }
    const committed = readJson(opts.out, "仓内产物")
    try {
      assertBuiltFromConsistency(committed, fresh, opts.out, sourcePath)
    } catch (err) {
      process.stderr.write(`[kb-view-sync] ✗ ${err instanceof Error ? err.message : String(err)}\n`)
      return 1
    }
    if (serialize(committed) !== freshText) {
      process.stderr.write(
        `[kb-view-sync] ✗ builtFrom 相同但消费面内容漂移（源生成逻辑或产物被手改）：${opts.out}\n`,
      )
      return 1
    }
    process.stdout.write(
      `[kb-view-sync] ✓ 一致：builtFrom=${fresh.builtFrom} schemaVersion=${fresh.schemaVersion} ` +
        `消费面 ${freshText.length}B / 源 ${sourceBytes}B\n`,
    )
    return 0
  }

  mkdirSync(dirname(opts.out), { recursive: true })
  writeFileSync(opts.out, freshText, "utf8")
  process.stdout.write(
    `[kb-view-sync] ✓ 写出 ${opts.out}\n` +
      `  builtFrom=${fresh.builtFrom} schemaVersion=${fresh.schemaVersion}\n` +
      `  collectionCounts=${JSON.stringify(fresh.collectionCounts)}\n` +
      `  体积 ${sourceBytes}B → ${freshText.length}B（content 类字段不入包）\n`,
  )
  return 0
}

// 仅作为 CLI 直接执行时跑 main；被 import（测试）时只导出纯函数。
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2))
  } catch (err) {
    if (err && err.code === "SOURCE_UNREADABLE") {
      process.stderr.write(`[kb-view-sync] ✗ ${err.message}\n`)
      process.exitCode = 2
    } else {
      process.stderr.write(`[kb-view-sync] ✗ ${err instanceof Error ? err.message : String(err)}\n`)
      process.exitCode = 2
    }
  }
}
