/**
 * 模型上下文窗口的唯一默认真源（单位：token）。
 *
 * ## 为什么需要一个保守默认值
 *
 * `maxContextSize` 只在「用户没设 + 没有预设」时走到这里：
 *   - `preset-resolver.ts` 的优先级是 `用户设置 ?? 预设 ?? 兜底`，
 *     24 个预设里 23 个带 `suggestedContextSize`，所以选具体预设的用户不受影响。
 *   - 唯一没有的是 `custom` 预设——它代表「未知模型」，兜底本来就该作用在这里。
 *   - 另外还会落到兜底的是：env 配置、全新 store、自定义模型未填。
 *
 * 对一个**未知窗口**的模型，猜错的代价不对称：
 *   - 猜大 → 请求超出模型窗口 → 上游硬失败 400，用户当场卡死。
 *   - 猜小 → 少用一些上下文 → 只是浪费容量，功能正常。
 *
 * 因此取 32K 这个下限档：只要模型窗口 ≥ 32K 就绝不会因默认值而 400。
 * 窗口更大的模型请从设置里选（选择器已提供 4K…1M 全部档位），
 * 或直接选一个预设——预设置自带正确的窗口值。
 *
 * ## 历史
 *
 * 此前这个兜底在仓里有五个不同数字（204800 / 204_800 / 131072 / 65536），
 * 其中 204800 对 32K 模型是 6 倍超窗。`agent-studio-projection.spec.ts`
 * 曾专门记录「两个真源不一致（204800 vs 131072）」——现在只剩这一个真源。
 *
 * 注意：`settings-model-list.ts` / `settings-model-test.ts` / `rerank.ts`
 * 里的 65536 是**辅助调用（列模型、探测、重排）的硬上限**，不是窗口默认值，
 * 概念不同，刻意不并入这里。
 */
export const DEFAULT_MAX_CONTEXT_TOKENS = 32_768
