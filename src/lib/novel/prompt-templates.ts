import { sliceChapterForReview } from "./chapter-window"
import { buildLanguageDirective } from "@/lib/output-language"

export const PROMPTS = {
  chapterGeneration: (contextPack: string, chapterGoal: string) =>
    [
      contextPack,
      "",
      "请根据以上上下文包和大纲，撰写以下章节：",
      chapterGoal,
      "",
      "要求：",
      "1. 严格遵循大纲中的情节走向",
      "2. 保持人物性格和说话方式一致",
      "3. 不要泄露角色尚不知道的信息",
      "4. 注意伏笔的埋设和回收",
      "5. 章节结尾要有钩子，吸引读者继续阅读",
      "6. 字数控制在 3000-5000 字",
    ].join("\n"),

  chapterContinuation: (contextPack: string, lastParagraph: string) =>
    [
      contextPack,
      "",
      "上一段内容：",
      lastParagraph,
      "",
      "请续写以下内容，保持风格和节奏一致：",
    ].join("\n"),

  chapterRevision: (contextPack: string, originalContent: string, revisionNotes: string) =>
    [
      contextPack,
      "",
      "原始章节内容：",
      originalContent.slice(0, 6000),
      "",
      "修改要求：",
      revisionNotes,
      "",
      "请根据修改要求重写章节，保持其他部分不变：",
    ].join("\n"),

  outlineGeneration: (genre: string, scale: string, premise: string, context = "") =>
    [
      `请为以下小说生成大纲：`,
      "",
      `类型：${genre}`,
      `规模：${scale}`,
      `核心设定：${premise}`,
      "",
      "已有故事记忆与项目资料（如果有）：",
      context || "暂无可用的剧情记忆、卡片故事或设定，请基于本次大纲提示词先生成初始版大纲。",
      "",
      buildLanguageDirective(premise),
      "",
      "请按审核表输出 Markdown。下列二级标题必须原样出现，不要改名：",
      "## 本卷目标",
      "写这一卷要达成的结果，以及谁挡住它。",
      "## 爽点节奏",
      "写这一卷的爽点落在哪些章。",
      "## 情绪弧线",
      "写情绪从哪里起、在哪里沉、在哪里抬。",
      "## 人物弧线",
      "写主要人物的动机、关系变化，和这一卷结束时的状态。",
      "## 伏笔布局",
      "用表格，列必须是：| ID | 内容 | 优先级 | 预计回收时机 |",
      "每一行的预计回收时机都要写成具体章节，不能空，不能写占位符。",
      "## 关键反转",
      "写这一卷的反转：之前读者以为什么，实际是什么。",
      "## 章节定位",
      "用表格，列必须是：| 章 | 定位 | 压力级 | 情绪强度 | 说明 |",
      "定位只能是：开场、发展、铺垫、转折、高潮、收束。压力级写 1 到 5 的整数，情绪强度写 1 到 10 的整数。每一章一行。",
      "每一章在表格之外再写四行：本章目标、冲突、转折、章尾钩子。",
      "人物设定要写姓名、性格、动机、人物弧线和关键关系。",
      "世界观要写规则、限制、代价、势力和重要地点。",
    ].join("\n"),

  outlineRefinementGeneration: (outlineContext: string, sectionHints: string, userRequest: string) =>
    [
      "请基于已有大纲和项目记忆，对小说进行一次统一的细化生成。",
      "",
      "硬性约束：",
      "1. 已有大纲、人物状态、角色认知、伏笔状态、时间线、正史规则和项目记忆都是最高优先级，不得推翻。",
      "2. 本次用户要求只能用于补充、聚焦和完善，不得改写既定主线和核心设定。",
      "3. 如果信息不足，只能做最小必要补完，且必须与现有设定兼容。",
      "",
      "已有大纲与项目记忆：",
      outlineContext,
      "",
      "本次细化重点：",
      userRequest.trim() || "未额外指定，请基于已有大纲与项目记忆完成全量细化。",
      "",
      buildLanguageDirective(userRequest || outlineContext),
      "",
      "请一次性覆盖以下 6 类细化内容：",
      sectionHints,
      "",
      "输出要求：",
      "1. 只返回一个 JSON 对象，不要输出解释、前言、额外说明或代码块外文本。",
      "2. JSON 必须包含以下 6 个字段，且每个字段的值都必须是字符串形式的中文 Markdown：",
      '   - "chapterOutlines"',
      '   - "characterBriefs"',
      '   - "organizationsOutline"',
      '   - "powerSystem"',
      '   - "foreshadowingPlan"',
      '   - "locationsOutline"',
      "3. chapterOutlines 必须逐章写出本章目标、冲突、转折、章尾钩子，并使用章纲审核表的标题：基础信息、本章目标、核心事件、场景顺序、章首钩子、爽点设计、章尾钩子、人物状态、伏笔与追踪。",
      "4. characterBriefs 必须覆盖人物动机、弧线、关系和当前状态。",
      "5. organizationsOutline、powerSystem、locationsOutline 必须写清规则、限制、代价、归属与剧情作用。",
      "6. foreshadowingPlan 必须体现伏笔的埋设、推进、回收节点和对应章节。",
    ].join("\n"),

  consistencyCheck: (contextPack: string, chapterContent: string) =>
    [
      contextPack,
      "",
      "请检查以下章节的连贯性：",
      sliceChapterForReview(chapterContent),
      "",
      "检查维度：",
      "1. 人设一致性",
      "2. 时间线准确性",
      "3. 伏笔状态",
      "4. 角色认知合理性",
      "5. 设定一致性",
    ].join("\n"),
} as const
